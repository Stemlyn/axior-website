// Pre-generates responsive WebP sizes of every brand photo into public/photos/opt/<name>-<width>.webp.
// The site serves these as cached static files (see src/lib/image-loader.ts) instead of resizing on
// every request. Re-run after adding or replacing a photo in public/photos.
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

export const WIDTHS = [320, 480, 750, 1080, 1440, 2000];
const SRC = "public/photos";
const OUT = `${SRC}/opt`;
mkdirSync(OUT, { recursive: true });

const max = {};
let total = 0;
for (const f of readdirSync(SRC).filter((n) => n.endsWith(".jpg")).sort()) {
  const name = f.replace(".jpg", "");
  const { width } = await sharp(`${SRC}/${f}`).metadata();
  max[name] = width;
  for (const w of WIDTHS.filter((x) => x <= width)) {
    const buf = await sharp(`${SRC}/${f}`).resize({ width: w }).webp({ quality: 62, effort: 6 }).toBuffer();
    writeFileSync(`${OUT}/${name}-${w}.webp`, buf);
    total += buf.length;
  }
}
writeFileSync(
  "src/lib/photo-sizes.ts",
  `// Generated by scripts/perf/make-photos.mjs: largest pre-generated width per photo.\nexport const PHOTO_WIDTHS = ${JSON.stringify(WIDTHS)} as const;\nexport const PHOTO_MAX: Record<string, number> = ${JSON.stringify(max)};\n`,
);
console.log(`wrote ${readdirSync(OUT).length} files, ${Math.round(total / 1024)} KB total`);
