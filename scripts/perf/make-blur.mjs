// Generates tiny blurred placeholders for the brand photos into src/lib/photo-blur.ts.
// Uses macOS `sips` (built in). Re-run after replacing a photo in public/photos.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const dir = "public/photos";
const tmp = mkdtempSync(join(tmpdir(), "blur-"));
const out = {};
for (const f of readdirSync(dir).filter((n) => n.endsWith(".jpg")).sort()) {
  const dst = join(tmp, f);
  execFileSync("sips", ["-Z", "16", "-s", "format", "jpeg", "-s", "formatOptions", "40", join(dir, f), "--out", dst], { stdio: "ignore" });
  out[f.replace(".jpg", "")] = `data:image/jpeg;base64,${readFileSync(dst).toString("base64")}`;
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: "${v}",`).join("\n");
writeFileSync(
  "src/lib/photo-blur.ts",
  `// Generated by scripts/perf/make-blur.mjs: 16 px previews shown (blurred) while each photo loads.\nexport const PHOTO_BLUR: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(out).length} placeholders, ${Math.round(JSON.stringify(out).length / 1024)} KB total`);
